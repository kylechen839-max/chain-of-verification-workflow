from __future__ import annotations

import json
import os
import re
import sqlite3
from contextlib import contextmanager
from typing import Any, Iterator
from urllib.parse import urlparse


SCHEMA_SQL = """
create table if not exists cove_evaluation_runs (
    id integer primary key autoincrement,
    created_at text not null default current_timestamp,
    model text not null,
    host text not null,
    question_file text not null,
    max_questions integer not null,
    num_predict integer not null,
    result_count integer not null,
    metadata_json text not null
);

create table if not exists cove_evaluation_results (
    id integer primary key autoincrement,
    run_id integer not null references cove_evaluation_runs(id) on delete cascade,
    question_id text not null,
    category text not null,
    question text not null,
    mode text not null,
    elapsed_seconds real not null,
    error text,
    answer_length integer not null,
    verification_question_count integer not null,
    manual_accuracy_score integer,
    manual_hallucination_score integer,
    manual_notes text not null default '',
    payload_json text not null
);

create index if not exists idx_cove_results_run_id
on cove_evaluation_results(run_id);

create index if not exists idx_cove_results_mode
on cove_evaluation_results(mode);
"""

POSTGRES_SCHEMA_SQL = """
create table if not exists {schema}.cove_evaluation_runs (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    model text not null,
    host text not null,
    question_file text not null,
    max_questions integer not null,
    num_predict integer not null,
    result_count integer not null,
    metadata_json jsonb not null
);

create table if not exists {schema}.cove_evaluation_results (
    id bigint generated by default as identity primary key,
    run_id bigint not null references {schema}.cove_evaluation_runs(id) on delete cascade,
    question_id text not null,
    category text not null,
    question text not null,
    mode text not null,
    elapsed_seconds double precision not null,
    error text,
    answer_length integer not null,
    verification_question_count integer not null,
    manual_accuracy_score integer,
    manual_hallucination_score integer,
    manual_notes text not null default '',
    payload_json jsonb not null
);

create index if not exists idx_cove_results_run_id
on {schema}.cove_evaluation_results(run_id);

create index if not exists idx_cove_results_mode
on {schema}.cove_evaluation_results(mode);
"""


def database_url_from_env() -> str | None:
    return (
        os.environ.get("COVE_DATABASE_URL")
        or os.environ.get("SUPABASE_DATABASE_URL")
        or os.environ.get("DATABASE_URL")
    )


def database_schema_from_env() -> str:
    return os.environ.get("COVE_DATABASE_SCHEMA") or "cove_test"


def validate_identifier(identifier: str) -> str:
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", identifier):
        raise ValueError(
            f"Invalid database schema name {identifier!r}. Use letters, numbers, and underscores."
        )
    return identifier


def is_sqlite_url(database_url: str) -> bool:
    parsed = urlparse(database_url)
    return parsed.scheme in {"", "sqlite", "sqlite3"}


def sqlite_path_from_url(database_url: str) -> str:
    parsed = urlparse(database_url)
    if parsed.scheme in {"sqlite", "sqlite3"}:
        if database_url.startswith(("sqlite:////", "sqlite3:////")):
            return parsed.path
        if database_url.startswith(("sqlite:///", "sqlite3:///")):
            return parsed.path.lstrip("/") or ":memory:"
        if parsed.netloc and parsed.netloc != ".":
            return f"/{parsed.netloc}{parsed.path}"
        return parsed.path or parsed.netloc
    return database_url


@contextmanager
def sqlite_connection(database_url: str) -> Iterator[sqlite3.Connection]:
    path = sqlite_path_from_url(database_url)
    if path in {"", ":memory:"}:
        path = ":memory:"
    conn = sqlite3.connect(path)
    conn.row_factory = sqlite3.Row
    try:
        conn.execute("pragma foreign_keys = on")
        yield conn
        conn.commit()
    finally:
        conn.close()


def initialize_sqlite(database_url: str) -> None:
    with sqlite_connection(database_url) as conn:
        conn.executescript(SCHEMA_SQL)


def save_report_sqlite(database_url: str, report: dict[str, Any]) -> int:
    initialize_sqlite(database_url)
    with sqlite_connection(database_url) as conn:
        cursor = conn.execute(
            """
            insert into cove_evaluation_runs (
                model, host, question_file, max_questions, num_predict,
                result_count, metadata_json
            )
            values (?, ?, ?, ?, ?, ?, ?)
            """,
            (
                report["model"],
                report["host"],
                report["question_file"],
                int(report["max_questions"]),
                int(report["num_predict"]),
                len(report["results"]),
                json.dumps(
                    {
                        "manual_scoring_scale": report.get("manual_scoring_scale", {}),
                    },
                    ensure_ascii=True,
                ),
            ),
        )
        run_id = int(cursor.lastrowid)

        for item in report["results"]:
            for mode_result in item["modes"]:
                conn.execute(
                    """
                    insert into cove_evaluation_results (
                        run_id, question_id, category, question, mode,
                        elapsed_seconds, error, answer_length,
                        verification_question_count, manual_accuracy_score,
                        manual_hallucination_score, manual_notes, payload_json
                    )
                    values (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                    """,
                    (
                        run_id,
                        item["id"],
                        item["category"],
                        item["question"],
                        mode_result["mode"],
                        float(mode_result["elapsed_seconds"]),
                        mode_result.get("error"),
                        int(mode_result.get("answer_length") or 0),
                        int(mode_result.get("verification_question_count") or 0),
                        mode_result.get("manual_accuracy_score"),
                        mode_result.get("manual_hallucination_score"),
                        mode_result.get("manual_notes", ""),
                        json.dumps(mode_result, ensure_ascii=True),
                    ),
                )

    return run_id


def save_report_postgres(database_url: str, report: dict[str, Any], schema: str) -> int:
    try:
        import psycopg
    except ImportError as exc:
        raise RuntimeError(
            "Postgres/Supabase writes require psycopg. Install dependencies with "
            "`python3 -m pip install -r requirements.txt`."
        ) from exc

    schema = validate_identifier(schema)
    metadata_json = json.dumps(
        {
            "manual_scoring_scale": report.get("manual_scoring_scale", {}),
        },
        ensure_ascii=True,
    )

    with psycopg.connect(database_url) as conn:
        with conn.cursor() as cursor:
            cursor.execute(f"create schema if not exists {schema}")
            cursor.execute(POSTGRES_SCHEMA_SQL.format(schema=schema))
            cursor.execute(
                f"""
                insert into {schema}.cove_evaluation_runs (
                    model, host, question_file, max_questions, num_predict,
                    result_count, metadata_json
                )
                values (%s, %s, %s, %s, %s, %s, %s::jsonb)
                returning id
                """,
                (
                    report["model"],
                    report["host"],
                    report["question_file"],
                    int(report["max_questions"]),
                    int(report["num_predict"]),
                    len(report["results"]),
                    metadata_json,
                ),
            )
            run_id = int(cursor.fetchone()[0])

            for item in report["results"]:
                for mode_result in item["modes"]:
                    cursor.execute(
                        f"""
                        insert into {schema}.cove_evaluation_results (
                            run_id, question_id, category, question, mode,
                            elapsed_seconds, error, answer_length,
                            verification_question_count, manual_accuracy_score,
                            manual_hallucination_score, manual_notes, payload_json
                        )
                        values (
                            %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s,
                            %s::jsonb
                        )
                        """,
                        (
                            run_id,
                            item["id"],
                            item["category"],
                            item["question"],
                            mode_result["mode"],
                            float(mode_result["elapsed_seconds"]),
                            mode_result.get("error"),
                            int(mode_result.get("answer_length") or 0),
                            int(mode_result.get("verification_question_count") or 0),
                            mode_result.get("manual_accuracy_score"),
                            mode_result.get("manual_hallucination_score"),
                            mode_result.get("manual_notes", ""),
                            json.dumps(mode_result, ensure_ascii=True),
                        ),
                    )

    return run_id


def save_report(database_url: str, report: dict[str, Any], schema: str | None = None) -> int:
    if is_sqlite_url(database_url):
        return save_report_sqlite(database_url, report)

    return save_report_postgres(database_url, report, schema or database_schema_from_env())
